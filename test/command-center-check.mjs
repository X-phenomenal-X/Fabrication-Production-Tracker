/* V2.1 domain regressions: persistence and metrics, without real floor data. */
import assert from 'node:assert/strict';
import { state, exportJson, loadLocal, mergeRecords, setTodo, deleteTodo } from '../js/store.js';
import { createOperation, commandSnapshot, operationHandoverLines, completeOperation } from '../js/command-center.js';
const memory = new Map();
globalThis.localStorage = { getItem: k => memory.get(k) ?? null, setItem: (k, v) => memory.set(k, v), removeItem: k => memory.delete(k) };
const ref = '2026-08-14';
const now = new Date(2026, 7, 14, 17);
state.todos = {}; state.tasks = []; state.machineConfig = {}; state.shiftLogs = {};
assert.throws(() => createOperation({ kind: 'downtime', text: 'Stopped', date: ref }), /machine/);
assert.throws(() => createOperation({ kind: 'quality', text: 'Marked', quantity: -1, date: ref }), /whole number/);
assert.throws(() => createOperation({ kind: 'action', text: 'Check', date: '2026-02-31' }), /date/);
const down = createOperation({ kind: 'downtime', text: 'Stopper cylinder', machine: 'fom2', assignee: 'Supervisor', date: ref });
const quality = createOperation({ kind: 'quality', text: 'Scratches', machine: 'fom3', quantity: 12, wo: 'TEST-1', date: ref });
const action = createOperation({ kind: 'action', text: 'Prepare next shift', date: '2026-08-13' });
let data = commandSnapshot(ref, now);
assert.equal(data.minutes, 0);
assert.equal(data.unknownMinutes, 1);
assert.equal(data.quality.length, 1);
assert.equal(data.open.length, 3);
assert.equal(data.machines.find(m => m.key === 'fom2').status, 'Reported down');
assert.equal(data.machines.some(m => m.queue), false);
assert.equal(data.documented, 0);
assert.equal(data.completed.length, 0);
assert.equal(operationHandoverLines(ref).length, 3);
const before = structuredClone(state.todos[down]);
createOperation({ id: down, kind: 'downtime', text: 'Stopper repaired', machine: 'fom2', minutes: 35, date: ref });
assert.equal(commandSnapshot(ref, now).minutes, 35);
assert.equal(commandSnapshot(ref, now).unknownMinutes, 0);
assert.equal(mergeRecords({ [down]: before }, { [down]: state.todos[down] })[down].operation.minutes, 35);
assert.equal(mergeRecords({ [down]: state.todos[down] }, { [down]: before })[down].operation.minutes, 35);
completeOperation(down);
assert.equal(commandSnapshot(ref, now).down.length, 0);
assert.equal(commandSnapshot(ref, now).minutes, 35, 'resolved losses remain in daily totals');
assert.ok(state.todos[down].doneAt);
setTodo(down, { done: false });
assert.equal(commandSnapshot(ref, now).down.length, 1, 'Today can reopen the same report');
const persisted = JSON.parse(exportJson());
state.todos = {};
loadLocal();
assert.deepEqual(state.todos[quality].operation, persisted.todos[quality].operation);
state.todos.future = { id: 'future', date: '2026-08-15', text: 'Future', done: false };
assert.equal(commandSnapshot(ref, now).open.length, 3, 'future actions do not enter this day');
state.machineConfig.fom1 = { hidden: true };
state.shiftLogs[`${ref}|AFT`] = { date: ref, shift: 'AFT', rows: { fom2: { notes: ' ' }, fom3: { next: 'Load material' } } };
assert.equal(commandSnapshot(ref, now).documented, 1, 'blank and ops-only rows are not handover coverage');
assert.equal(commandSnapshot(ref, now).machines.some(m => m.key === 'fom1'), false);
deleteTodo(action);
assert.equal(state.todos[action], undefined);
assert.ok(operationHandoverLines(ref).every(line => !line.includes('Prepare next shift')));
console.log('Command Center: persistence, merge, validation, downtime, quality, carryover and handover OK');
