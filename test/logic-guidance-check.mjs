import assert from 'node:assert/strict';
import { state, setTodo } from '../js/store.js';
import { createOperation, commandSnapshot, commandSuggestions, operationHandoverLines } from '../js/command-center.js';
import { toggleDowntime, validCalendarDate } from '../js/floor-operations.js';
import { supervisorSummary, REPORT_NOTE } from '../js/views/supervisor-report.js';

// Run in UTC and America/Toronto: completion must use the device calendar day.
const memory = new Map();
globalThis.localStorage = { getItem:k=>memory.get(k)??null, setItem:(k,v)=>memory.set(k,v), removeItem:k=>memory.delete(k) };
state.tasks=[]; state.todos={}; state.machineConfig={}; state.shiftLogs={};
const ref='2026-08-14', now=new Date(2026,7,15,0,30);
for (const bad of ['2026-02-31','2026-13-01','x','2026-2-01']) assert.equal(validCalendarDate(bad),false);
assert.equal(validCalendarDate('2024-02-29'),true);
assert.throws(()=>supervisorSummary('2026-02-31',ref,now),/valid date/);
assert.throws(()=>supervisorSummary(ref,'2026-08-16',now),/future/);
assert.throws(()=>supervisorSummary('2026-01-01',ref,now),/31 days/);
assert.equal(supervisorSummary(ref,ref,now).recordCount,0);
assert.match(REPORT_NOTE,/not a confirmed loss-free day/);
state.todos.done={id:'done',date:ref,done:true,doneAt:new Date(2026,7,14,23,45).toISOString()};
state.todos.reopened={id:'reopened',date:ref,done:false,doneAt:state.todos.done.doneAt};
assert.equal(supervisorSummary(ref,ref,now).daily[0][5],1,'local completion day; reopened reports are not resolved');
assert.equal(supervisorSummary('2026-08-15','2026-08-15',now).daily[0][5],0);
state.todos={};
const id=createOperation({kind:'downtime',text:'Timer review',machine:'fom2',date:ref});
toggleDowntime(id,new Date(2026,7,14,23,45));
assert.match(operationHandoverLines(ref,now)[0],/45 min reported.*timer still running/);
assert.equal(commandSnapshot(ref,now).machines.find(m=>m.key==='fom2').status,'Reported down');
assert.equal(commandSuggestions(commandSnapshot(ref,now),ref)[0].key,'running-loss');
toggleDowntime(id,now);
let machine=commandSnapshot(ref,now).machines.find(m=>m.key==='fom2');
assert.equal(machine.status,'Verify machine status'); assert.equal(machine.tone,'warn');
assert.match(operationHandoverLines(ref,now)[0],/verify machine status/);
state.machineConfig.fom2={label:'Custom FOM'};
state.shiftUpdate={date:ref,shift:'AFT',machines:{fom2:{down:true}}};
assert.equal(commandSnapshot(ref,now).machines.find(m=>m.key==='fom2').status,'Check down report','workbook down flag remains visible');
assert.equal(supervisorSummary(ref,ref,now).causes[0][0],'Custom FOM · Other');
assert.throws(()=>createOperation({id,kind:'quality',text:'Convert',machine:'fom2',date:ref}),/type cannot/);
assert.throws(()=>createOperation({kind:'quality',text:'Bad photo',date:ref,details:{photos:[null]}}),/JPEG/);
setTodo(id,{done:true});
const older=createOperation({kind:'action',text:'Older non-urgent',date:'2026-08-01'});
const due=createOperation({kind:'action',text:'Overdue',date:ref,dueDate:'2026-08-13'});
const quality=createOperation({kind:'quality',text:'Inspect marks',date:ref});
let data=commandSnapshot(ref,now);
assert.ok(data.open.indexOf(state.todos[due])<data.open.indexOf(state.todos[older]));
let suggestions=commandSuggestions(data,ref);
assert.equal(suggestions[0].key,'quality-containment');
assert.ok(suggestions.some(s=>s.key==='overdue'&&s.report.id===due));
assert.ok(suggestions.some(s=>s.key==='setup'));
assert.ok(suggestions.some(s=>s.key==='handover'));
setTodo(quality,{done:true}); setTodo(due,{done:true});
suggestions=commandSuggestions(commandSnapshot(ref,now),ref);
assert.ok(!suggestions.some(s=>['quality-containment','overdue','running-loss','verify-machine'].includes(s.key)));
console.log('Logic guidance: local dates, evidence limits, timer status, live handover minutes, priority and suggestions OK');
