import assert from 'node:assert/strict';
import { state, setTodo, saveShiftLog, exportJson, loadLocal } from '../js/store.js';
import { createOperation } from '../js/command-center.js';
import { elapsedMinutes, lossMinutesOn, toggleDowntime, handoverSignature, handoverAcknowledged, reportCsv } from '../js/floor-operations.js';
import { supervisorSummary } from '../js/views/supervisor-report.js';
const memory = new Map();
globalThis.localStorage = {getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
state.todos={}; state.shiftLogs={};
const id=createOperation({kind:'downtime',text:'Timer test',machine:'fom2',date:'2026-08-14',details:{reason:'Equipment',maintenance:'Notified',planned:false}});
const start=new Date(2026,7,14,23,45), end=new Date(2026,7,15,0,15);
toggleDowntime(id,start);
assert.equal(elapsedMinutes(state.todos[id].operation,end),30);
assert.equal(lossMinutesOn(state.todos[id],'2026-08-14',end),15);
assert.equal(lossMinutesOn(state.todos[id],'2026-08-15',end),15);
const duplicate=createOperation({kind:'downtime',text:'Duplicate',machine:'fom2',date:'2026-08-14'});
assert.throws(()=>toggleDowntime(duplicate,start),/already running/);
toggleDowntime(id,end);
assert.equal(state.todos[id].operation.minutes,30);
createOperation({id,kind:'downtime',text:'Edited',machine:'fom2',date:'2026-08-14',minutes:999});
assert.equal(state.todos[id].operation.minutes,30);
assert.equal(state.todos[id].operation.maintenance,'Notified');
toggleDowntime(id,new Date(2026,7,15,0,30));
toggleDowntime(id,new Date(2026,7,15,0,40));
assert.equal(elapsedMinutes(state.todos[id].operation),40);
toggleDowntime(id,new Date()); setTodo(id,{done:true});
assert.equal(state.todos[id].operation.timer.startedAt,null,'Today completion stops timer');
setTodo(id,{done:false});
assert.equal(state.todos[id].operation.timer.startedAt,null,'reopening does not restart timer');
const quality=createOperation({kind:'quality',text:'Scratches',date:'2026-08-14',details:{containment:'Hold tagged stock',rejected:3,qualityState:'Contained',photos:[{name:'test.jpg',data:'data:image/jpeg;base64,/9j/'}]}});
assert.throws(()=>createOperation({kind:'quality',text:'Bad',details:{rejected:-1}}),/whole number/);
assert.throws(()=>createOperation({kind:'quality',text:'Bad',details:{photos:[{data:'data:image/svg+xml,unsafe'}]}}),/JPEG/);
createOperation({id:quality,kind:'quality',text:'Edited scratches',date:'2026-08-14'});
assert.equal(state.todos[quality].operation.containment,'Hold tagged stock');
assert.equal(state.todos[quality].operation.photos.length,1);
saveShiftLog('2026-08-14','AFT',{notes:'Review reports',rows:{}});
let log=state.shiftLogs['2026-08-14|AFT'];
assert.ok(log.carryover.some(t=>t.id===quality));
saveShiftLog(log.date,log.shift,{acknowledgement:{by:'Incoming',at:end.toISOString(),signature:handoverSignature(log)}});
assert.ok(handoverAcknowledged(state.shiftLogs['2026-08-14|AFT']));
saveShiftLog(log.date,log.shift,{notes:'Updated notes'});
assert.equal(handoverAcknowledged(state.shiftLogs['2026-08-14|AFT']),false);
const before=JSON.parse(exportJson()); state.todos={};loadLocal();
assert.deepEqual(state.todos[quality].operation,before.todos[quality].operation);
assert.match(reportCsv([['=HYPERLINK("bad")']]),/"'=HYPERLINK/);
assert.throws(()=>supervisorSummary('2026-01-01','2026-03-01'),/31 days/);
assert.equal(supervisorSummary('2026-08-14','2026-08-14',end).daily[0][1],15);
console.log('V2.2: timer lifecycle, date splitting, quality evidence, carryover, acknowledgement and CSV safeguards OK');
